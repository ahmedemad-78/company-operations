/**
 * ضبط التوقيت على القاهرة قبل أي طلب.
 *
 * كل منطق النظام مبني على "اليوم" بالتوقيت المحلي: الإقفال اليومي، ترحيل الرصيد،
 * تسجيل الحضور، وفترة المرتب. وسيرفرات الاستضافة تعمل بتوقيت UTC، فبدون هذا الضبط
 * يختلف اليوم بين منتصف الليل والثالثة صباحًا بتوقيت مصر.
 *
 * Vercel يحجز اسم متغير البيئة `TZ`، فنستخدم `APP_TIMEZONE` بدلًا منه.
 * `register` تُنفَّذ مرة واحدة عند بدء كل نسخة من السيرفر وقبل أول طلب.
 */
export function register() {
  process.env.TZ = process.env.APP_TIMEZONE || "Africa/Cairo";
}
